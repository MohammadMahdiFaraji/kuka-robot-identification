function run_all(mode)
% RUN_ALL  Reproduce and check the paper, from the raw recordings of the robot to the result tables:
%
%   J. Weigand, J. Goetz, J. Ulmen, M. Ruskowski, "Dataset and Baseline for an Industrial Robot
%   Identification Benchmark", version 2.0, April 9, 2023 (version 1: January 26, 2022).
%
%   run_all          steps 1-8, about 4.5 minutes. Step 7 uses the version 1 ssest model that was
%                    trained again once and saved in results/models.
%   run_all('full')  first step 7a: train that ssest model again from scratch (about 2.3 hours),
%                    then steps 1-8 with it. The saved model is replaced only when the training
%                    has finished, so an interrupted run changes nothing.
%
% Steps (one log file per step in results/logs):
%   1   raw recordings -> benchmark files (official script and Listing 1)    Sec. 2.2, Tab. 1, 3
%   2   excitation trajectories, eq. (1)-(2), limits                          Sec. 2.1, Tab. 7
%   3   sensors, controller, inputs of the inverse dataset                    Tab. 2, 3, 10, App. A, C
%   4   forward baseline v2 (n4sid)       -> Table 4, Fig. 7                  Sec. 5.1, Listing 2
%   5   inverse baseline v2 (fminunc)     -> Table 5, Fig. 8                  Sec. 5.2, Listing 3
%   6   v1 baselines (authors' models)    -> v1 Tables 4, 5, Fig. 9           v1, changelog
%   7a  v1 ssest model trained again (only with 'full')                       v1 Listing 2
%   7   v1 baselines trained again        -> v1 Tables 4, 5                   v1 Listing 2
%   8   statements of Sec. 5, Figs. 2-6, consistency of the text, observations
%
% Outputs in results/: all_checks.csv (every checked statement), summary.txt, tables/ (the
% result tables, paper against ours), figures/ (Figs. 2-9), models/, logs/.
%
% The official data archive must be in data/ (see data/README.md).
%
% MohammadMahdi Faraji, mmyasharfaraji@gmail.com

if nargin < 1
    mode = 'quick';
end
here = fileparts(mfilename('fullpath'));
addpath(fullfile(here, 'functions'), fullfile(here, 'steps'));
folder = find_data(here);
results = fullfile(here, 'results');
logs = fullfile(results, 'logs');
subfolders = {results, logs, fullfile(results, 'tables'), fullfile(results, 'figures'), fullfile(results, 'models')};
for i = 1:numel(subfolders)
    if ~exist(subfolders{i}, 'dir')
        mkdir(subfolders{i});
    end
end
start = tic;

if strcmp(mode, 'full')
    % train into a new file first; the old model stays until the training has finished
    fw = load(fullfile(folder, 'forward_identification_without_raw_data.mat'));
    model_file = fullfile(results, 'models', 'v1_ssest_retrained.mat');
    new_file = fullfile(results, 'models', 'v1_ssest_retrained_new.mat');
    running_log = fullfile(logs, 'step7a_retrain_v1_ssest_RUNNING.log');
    start_log(running_log);
    step7a_retrain_v1_ssest(fw, new_file);
    diary('off');
    movefile(new_file, model_file, 'f');
    movefile(running_log, fullfile(logs, 'step7a_retrain_v1_ssest.log'), 'f');
end

start_log(fullfile(logs, 'step0_load_data.log'));
fprintf('MATLAB %s\ndata: data/%s\n', version, 'Robot_Identification_Benchmark_With_Raw_Data');
data = load_all_data(folder, results);
diary('off');

steps = {'step1_dataset_from_raw', 'step2_experiment_design', 'step3_sensors_controller_inverse', ...
         'step4_forward_baseline_v2', 'step5_inverse_baseline_v2', 'step6_v1_baselines', ...
         'step7_v1_retrained', 'step8_section5_figures_text'};
checks = [];
step_of_check = {};
for k = 1:numel(steps)
    fprintf('\n===== %s =====\n', steps{k});
    start_log(fullfile(logs, [steps{k} '.log']));
    [new_checks, data] = feval(steps{k}, data);
    diary('off');
    checks = [checks new_checks];
    step_of_check = [step_of_check repmat(steps(k), 1, numel(new_checks))];
end

% ---- the list of all checks, the result tables and the summary
T = struct2table(checks);
T.step = step_of_check';
T = T(:, {'id', 'step', 'section', 'claim', 'paper', 'reproduced', 'status'});
writetable(T, fullfile(results, 'all_checks.csv'));

fid = fopen(fullfile(results, 'tables', 'paper_tables_reproduced.md'), 'w', 'n', 'UTF-8');
fprintf(fid, ['# Result tables of the paper, recomputed\n\nPer-joint values are rounded to 3 decimals as in the paper; ' ...
    '"all joints" is the mean of the rounded values. Generated by run_all.m (MATLAB %s).\n\n%s'], version, data.md);
fclose(fid);

statuses = {'MATCH', 'CONSISTENT', 'DEVIATION', 'UNDOCUMENTED', 'UNCLEAR', 'OBSERVATION'};
fid = fopen(fullfile(results, 'summary.txt'), 'w', 'n', 'UTF-8');
fprintf(fid, 'MATLAB %s\n\n', version);
for s = 1:numel(statuses)
    fprintf(fid, '%-13s %2d\n', statuses{s}, sum(strcmp(T.status, statuses{s})));
end
n_obs = sum(strcmp(T.status, 'OBSERVATION'));
fprintf(fid, '%-13s %2d (%d claims of the paper + %d observations)\n\n', 'total', height(T), height(T) - n_obs, n_obs);
for i = 1:height(T)
    fprintf(fid, '%-5s %-12s %s\n', T.id{i}, T.status{i}, T.claim{i});
end
fclose(fid);
type(fullfile(results, 'summary.txt'));
fprintf('\nfinished in %.0f s\n', toc(start));
end

function folder = find_data(here)
% the official archive: data/Robot_Identification_Benchmark_With_Raw_Data, or its contents directly in data/
name = 'Robot_Identification_Benchmark_With_Raw_Data';
candidates = {fullfile(here, 'data', name), fullfile(here, 'data')};
for i = 1:numel(candidates)
    c = candidates{i};
    if exist(fullfile(c, 'raw_data'), 'dir') && exist(fullfile(c, 'forward_identification_without_raw_data.mat'), 'file')
        folder = c;
        return
    end
end
error('run_all:data', ['The official data archive "%s" was not found in data/. Download it from ' ...
    'https://doi.org/10.26204/data/5 (see data/README.md).'], name);
end

function start_log(file)
% write everything that is printed from now on also into file (until diary('off'))
if exist(file, 'file')
    delete(file);
end
diary(file);
end
